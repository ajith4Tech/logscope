"""Write logscope/_version.py (generated at build time, gitignored).

    python packaging/write_version.py VERSION [REVISION]

VERSION is normally `git describe --tags --always --dirty` (the Makefile and
CI pass it as the VERSION build argument).
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

_TARGET = Path(__file__).resolve().parents[1] / "logscope" / "_version.py"
_SAFE = re.compile(r"^[0-9A-Za-z][0-9A-Za-z._+-]{0,127}$")


def main(argv: list[str]) -> int:
    if not 1 <= len(argv) <= 2:
        print(__doc__, file=sys.stderr)
        return 2
    version, revision = argv[0].strip(), (argv[1].strip() if len(argv) > 1 else "")
    for name, value in (("VERSION", version), ("REVISION", revision)):
        if value and not _SAFE.match(value):
            print(f"invalid {name}: {value!r}", file=sys.stderr)
            return 2
    if not version:
        print("VERSION must not be empty", file=sys.stderr)
        return 2
    _TARGET.write_text(
        "# Generated by packaging/write_version.py at build time. Do not edit or commit.\n"
        f"__version__ = {version!r}\n"
        f"__revision__ = {revision!r}\n"
    )
    print(f"{_TARGET.name}: {version} {revision}".rstrip())
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
